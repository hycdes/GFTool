# -*- coding: utf-8 -*-
"""Refresh T-Doll skill icons from the official GF2 wiki API.

Rules:
  * Icon source: POST https://gf2-bbs-api.exiliumgf.com/wiki/hero_detail
    -> data.info.skill[].desc, first <img src="...">.
  * Every icon is resized to 128x128 PNG.
  * Naming: NAME_skill_NO.png (NAME = doll id without SSR/SR suffix).
  * Normal attack: if it uses a generic Skill_Attack_*.png, keep the existing
    generic icon and do not create a new file; otherwise use NO=00.
  * Other skills: numbered 01, 02, 03, ... in display order.

Usage:
    py -3 scripts/scrape_skill_icons.py [--dry-run] [--force] [--only ID]
"""
import argparse
import io
import json
import os
import re
import sys
import time
import urllib.request

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
DATA_PATH = os.path.join(ROOT, 'dat', 'tdoll_stat.js')
SKILL_DIR = os.path.join(ROOT, 'img', 'skill')
API = 'https://gf2-bbs-api.exiliumgf.com/wiki/hero_detail'
UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64)'


def load_dolls():
    raw = open(DATA_PATH, encoding='utf-8').read()
    start = raw.find('window.TDOLL_STAT')
    return json.loads(raw[raw.find('=', start) + 1:raw.rfind('}') + 1])


def write_dolls(data):
    with open(DATA_PATH, 'w', encoding='utf-8', newline='\n') as fp:
        fp.write('// GF2 Tools T-Doll data\n')
        fp.write('// Generated by scripts/scrape_local.py from the local game client.\n')
        fp.write('// Fields: id, name, rank, tags, intro, avatar, thumbnail, attrGroups, skills\n')
        fp.write('// skill: { name, icon, tags, subTags, meta, levels, desc, descs, descRefs, vertebrae }\n')
        fp.write('window.TDOLL_STAT = ')
        json.dump(data, fp, ensure_ascii=False, separators=(',', ':'))
        fp.write(';\n')


def norm(name):
    name = (name or '').strip()
    if '·' in name:
        name = name.split('·', 1)[1].strip()
    return name


def post_json(url, payload, retries=3):
    body = json.dumps(payload).encode()
    last = None
    for _ in range(retries):
        try:
            req = urllib.request.Request(url, data=body, headers={
                'Content-Type': 'application/json',
                'User-Agent': UA,
            })
            with urllib.request.urlopen(req, timeout=30) as r:
                return json.loads(r.read())
        except Exception as exc:  # noqa: BLE001
            last = exc
            time.sleep(1)
    raise last


def fetch_heroes(name_to_id):
    heroes = {}
    for hero_id in range(1001, 1100):
        try:
            o = post_json(API, {'id': hero_id})
        except Exception:
            continue
        if o.get('Code') != 0:
            continue
        info = o['data']['info']
        did = name_to_id.get(info.get('name'))
        if not did:
            continue
        skills = []
        for s in info.get('skill') or []:
            desc = s.get('desc') or ''
            m = re.search(r'<img[^>]*src="([^"]+)"', desc)
            skills.append({'name': s.get('name') or '', 'icon': m.group(1) if m else ''})
        heroes[did] = skills
    return heroes


def match_official(local_skill, index, official, used):
    key = norm(local_skill.get('name'))
    for e in official:
        if id(e) not in used and norm(e.get('name')) == key:
            return e
    for e in official:
        if id(e) in used:
            continue
        on = norm(e.get('name'))
        if key and on and (key in on or on in key):
            return e
    if index < len(official) and id(official[index]) not in used:
        return official[index]
    for e in official:
        if id(e) not in used:
            return e
    return None


def icon_url(url):
    """A few official skill icons still point at the old mcc /image/ path."""
    if url and 'gf2.mcc.wiki/image/skill/' in url:
        return url.replace('/image/skill/', '/static/thumbnail/skill/')
    return url


def download_icon(url, dest, force=False):
    url = icon_url(url)
    if not url:
        return False
    if os.path.exists(dest) and not force:
        return True
    os.makedirs(os.path.dirname(dest), exist_ok=True)
    last = None
    for _ in range(3):
        try:
            req = urllib.request.Request(url, headers={'User-Agent': UA})
            raw = urllib.request.urlopen(req, timeout=30).read()
            img = Image.open(io.BytesIO(raw)).convert('RGBA').resize((128, 128), Image.LANCZOS)
            img.save(dest)
            return True
        except Exception as exc:  # noqa: BLE001
            last = exc
            time.sleep(1)
    print('  ! icon failed:', url, last)
    return False


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--dry-run', action='store_true')
    ap.add_argument('--force', action='store_true')
    ap.add_argument('--only', help='only process one doll id')
    args = ap.parse_args()

    data = load_dolls()
    name_to_id = {d['name']: did for did, d in data.items()}
    print('fetching official hero data ...')
    heroes = fetch_heroes(name_to_id)
    print('official dolls:', len(heroes))

    downloaded = 0
    generic = 0
    unmatched = []
    failed = []
    for did, doll in data.items():
        if args.only and did != args.only:
            continue
        official = heroes.get(did)
        if not official:
            print('! no official data:', did, doll.get('name'))
            continue
        base = re.sub(r'(SSR|SR)$', '', did)
        used = set()
        seq = 0
        for index, skill in enumerate(doll.get('skills') or []):
            official_skill = match_official(skill, index, official, used)
            if official_skill is None:
                unmatched.append((did, skill.get('name')))
                continue
            used.add(id(official_skill))

            is_normal = '普攻' in (skill.get('tags') or [])
            old_icon = skill.get('icon') or ''
            old_name = os.path.basename(old_icon)
            if is_normal and old_name.startswith('Skill_Attack_'):
                generic += 1
                continue

            if is_normal:
                no = 0
            else:
                seq += 1
                no = seq
            filename = '%s_skill_%02d.png' % (base, no)
            dest = os.path.join(SKILL_DIR, filename)
            rel = 'img/skill/' + filename
            if args.dry_run:
                print('%-28s %-10s %s -> %s' % (did, skill.get('name'), old_name, filename))
                continue
            if download_icon(official_skill.get('icon'), dest, args.force):
                skill['icon'] = rel
                downloaded += 1
            else:
                failed.append((did, skill.get('name'), official_skill.get('icon')))

    if not args.dry_run:
        write_dolls(data)
    print('downloaded/updated:', downloaded, 'generic kept:', generic,
          'unmatched:', len(unmatched), 'failed:', len(failed))
    for row in unmatched:
        print('  unmatched:', row)
    for row in failed:
        print('  failed:', row)


if __name__ == '__main__':
    main()
