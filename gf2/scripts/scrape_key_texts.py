# -*- coding: utf-8 -*-
"""Build rich mind-spiral key descriptions from the local game client.

`key_stat.js` keeps the icon/name/attrs from the official API.  The
description text and mechanic-term references are local game data:
  TalentKeyData.f6 -> BattleSkillDisplayData.f3 (text) / f4 (refs)

Outputs:
  dat/key_desc_stat.js   keyId -> {text, refs}
  dat/term_stat.js       merges terms referenced by key descriptions
"""
import io
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)

import scrape_local as s  # noqa: E402

KEY_PATH = os.path.join(ROOT, 'dat', 'key_stat.js')
DESC_PATH = os.path.join(ROOT, 'dat', 'key_desc_stat.js')
TERM_PATH = os.path.join(ROOT, 'dat', 'term_stat.js')


def load_js(path, var):
    raw = io.open(path, encoding='utf-8').read()
    i = raw.find(var)
    return json.loads(raw[raw.find('=', i) + 1:raw.rfind('}') + 1])


def main():
    keys = load_js(KEY_PATH, 'window.KEY_STAT')
    terms = load_js(TERM_PATH, 'window.TERM_STAT')
    t = s.Tables(s.DEFAULT_TABLE)
    store = s.TermStore(t)

    display = {r.get(1): r for r in t.rows('BattleSkillDisplayData') if isinstance(r.get(1), int)}
    by_name = {}
    for r in t.rows('TalentKeyData'):
        name = t.text(r.get(7))
        if name and name not in by_name:
            by_name[name] = r

    out = {}
    refs_list = []
    placeholder_count = 0
    unresolved = []
    for doll_id, doll in keys.get('byDoll', {}).items():
        for category in ('shared', 'fixed', 'leap'):
            vals = doll.get(category)
            if not vals:
                continue
            if isinstance(vals, dict):
                vals = [vals]
            for key in vals:
                row = by_name.get(key.get('name'))
                if not row:
                    continue
                skill_id = row.get(6)
                disp = display.get(skill_id)
                if not disp:
                    continue
                text = t.text(disp.get(3)) or ''
                if not text:
                    continue
                refs = store.resolve(s.parse_refs(t.text(disp.get(4))))
                out[key.get('id') or key.get('name')] = {'text': text, 'refs': refs}
                refs_list.append(refs)
                for n in sorted(set(int(x) for x in re.findall(r'\{(\d+)\}', text))):
                    placeholder_count += 1
                    if n >= len(refs) or refs[n][1] is None:
                        unresolved.append((doll_id, key.get('name'), n, refs))

    with io.open(DESC_PATH, 'w', encoding='utf-8', newline='\n') as fp:
        fp.write('// GF2 Tools mind-spiral key rich descriptions\n')
        fp.write('// Generated by scripts/scrape_key_texts.py from the local game client.\n')
        fp.write('// keyId -> { text, refs }\n')
        fp.write('window.KEY_DESC_STAT = ')
        json.dump(out, fp, ensure_ascii=False, separators=(',', ':'))
        fp.write(';\n')

    new_terms = store.collect(refs_list)
    added = 0
    for k, v in new_terms.items():
        if k not in terms:
            terms[k] = v
            added += 1
    with io.open(TERM_PATH, 'w', encoding='utf-8', newline='\n') as fp:
        fp.write('// GF2 Tools battle dictionary / buff terms\n')
        fp.write('// Generated by scripts/scrape_local.py from the local game client.\n')
        fp.write('window.TERM_STAT = ')
        json.dump(terms, fp, ensure_ascii=False, separators=(',', ':'))
        fp.write(';\n')

    print('keys enriched:', len(out))
    print('placeholders:', placeholder_count, 'unresolved:', len(unresolved))
    for row in unresolved[:10]:
        print('  unresolved:', row)
    print('terms added:', added, 'total:', len(terms))


if __name__ == '__main__':
    main()
